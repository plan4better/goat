// Generates lib/style/generated/ from goatlib's GOAT Style data: the TypeScript types of the JSON Schema, the
// palette, icon and emoji catalogues with the icon groups, the property kinds and capabilities, the reference defaults and
// default ranges; and from the library icons' SVGs, the picker's symbols file (public/assets/icons/maki/symbols.json). The web build does not see packages/python (turbo prune), so the app reads these copies;
// lib/style/__tests__/generated.test.ts fails when they no longer match goatlib. Run: pnpm --filter @p4b/web generate:style
import { compile } from "json-schema-to-typescript";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { format, resolveConfig } from "prettier";

const WEB = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const DATA = resolve(WEB, "../../packages/python/goatlib/src/goatlib/style/data");
const BANNER =
  "/* eslint-disable */\n// Generated by scripts/generate-style-sources.mjs from goatlib's GOAT Style data. Do not edit.\n";

const read = (name) => JSON.parse(readFileSync(resolve(DATA, name), "utf8"));

const constant = (name, type, value) =>
  `${BANNER}\nexport const ${name}: ${type} = ${JSON.stringify(value, null, 2)};\n`;

/** Every `$ref` target inside a property schema. */
function refs(node, found = []) {
  if (Array.isArray(node)) node.forEach((item) => refs(item, found));
  else if (node && typeof node === "object") {
    if (typeof node.$ref === "string") found.push(node.$ref.replace("#/$defs/", ""));
    Object.values(node).forEach((value) => refs(value, found));
  }
  return found;
}

/** The schema without property titles (the root's title and id are dropped by the caller): json-schema-to-typescript names a type after its title,
 * so property titles ("Fill", "Color") would take the names of the definitions (the interface `Fill` would become
 * `Fill1`). Definitions keep their names. */
function untitled(node) {
  if (Array.isArray(node)) return node.map((item) => untitled(item));
  if (!node || typeof node !== "object") return node;
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    if (key === "properties" && value && typeof value === "object" && !Array.isArray(value)) {
      out[key] = Object.fromEntries(
        Object.entries(value).map(([name, property]) => {
          const { title: _title, ...rest } = property;
          return [name, untitled(rest)];
        })
      );
    } else {
      out[key] = untitled(value);
    }
  }
  return out;
}

/** Every part key with its property schema (`fill.color`, `label.halo.width`), zoom ranges left out. */
function partProperties(schema) {
  const defs = schema.$defs;
  const out = [];
  for (const [part, partSchema] of Object.entries(defs.Symbol.properties)) {
    const model = refs(partSchema)[0];
    for (const [key, property] of Object.entries(defs[model].properties)) {
      if (key === "min_zoom" || key === "max_zoom") continue;
      if (key === "halo" || key === "font") {
        const sub = refs(property)[0];
        for (const [subKey, subProperty] of Object.entries(defs[sub].properties))
          out.push([`${part}.${key}.${subKey}`, subProperty]);
      } else {
        out.push([`${part}.${key}`, property]);
      }
    }
  }
  return out.sort(([a], [b]) => a.localeCompare(b));
}

/** color, number or choice for every part key, as goatlib derives its target kinds from the models. */
function propertyKinds(schema) {
  const kindOf = (property) => {
    const targets = refs(property);
    if (targets.includes("ByAttributeColor")) return "color";
    if (targets.includes("ByAttributeNumber")) return "number";
    return "choice";
  };
  return Object.fromEntries(partProperties(schema).map(([key, property]) => [key, kindOf(property)]));
}

/** The value forms each property takes (spec 4.5), from the forms its schema allows: zoom stops that blend or step,
 * values by attribute, and whether classes and rules may set it. A zoom-only number (arrows spacing, offsets) is a
 * number here, where PROPERTY_KINDS keeps the compiler's choice. */
/** Whether a property's fixed value is a number: a number that switches at zoom stops is still a number. */
const fixedNumber = (property) =>
  (property.anyOf ?? []).some((branch) => (branch.oneOf ?? [branch]).some((b) => b.type === "number"));

function capabilities(schema) {
  const defs = schema.$defs;
  const perLayer = new Set(schema["x-per-layer"]);
  const capability = (property, perFeature) => {
    const targets = refs(property);
    const zoom = targets.some((t) => t.startsWith("ZoomStep"))
      ? "step"
      : targets.some((t) => t.startsWith("Zoom"))
        ? "blend"
        : null;
    const attribute = targets.includes("ByAttributeColor")
      ? "color"
      : targets.includes("ByAttributeNumber")
        ? "number"
        : null;
    const kind = attribute ?? (zoom === "blend" || fixedNumber(property) ? "number" : "choice");
    return { kind, zoom, attribute, perFeature };
  };
  const caps = Object.fromEntries(
    partProperties(schema).map(([key, property]) => [key, capability(property, !perLayer.has(key))])
  );
  caps.opacity = capability(defs.VectorStyle.properties.opacity, false);
  caps["raster.opacity"] = capability(defs.RasterStyle.properties.opacity, false);
  for (const key of ["radius", "intensity", "opacity"])
    caps[`heatmap.${key}`] = capability(defs.HeatmapRender.properties[key], false);
  return Object.fromEntries(Object.entries(caps).sort(([a], [b]) => a.localeCompare(b)));
}

function capabilitiesModule(schema) {
  return (
    `${BANNER}\nexport interface Capability {\n  kind: "color" | "number" | "choice";\n  zoom: "blend" | "step" | null;\n` +
    `  attribute: "color" | "number" | null;\n  perFeature: boolean;\n}\n\n` +
    `export const CAPABILITIES: Readonly<Record<string, Capability>> = ${JSON.stringify(capabilities(schema), null, 2)};\n\n` +
    `/** The range a number target spreads its classes or values over when the style gives none (goatlib default_range). */\n` +
    `export const DEFAULT_RANGES: Readonly<Record<string, readonly [number, number]>> = ${JSON.stringify(schema["x-default-ranges"], null, 2)};\n\n` +
    `/** The default range of a property: by its full key, else by its last segment (\"outline.width\" -> \"width\"). */\n` +
    `export function defaultRange(key: string): [number, number] {\n` +
    `  const range = DEFAULT_RANGES[key] ?? DEFAULT_RANGES[key.split(".").pop() ?? key] ?? [0, 1];\n` +
    `  return [range[0], range[1]];\n}\n`
  );
}

const ICONS = resolve(WEB, "public/assets/icons/maki");
const SVG_ELEMENTS = new Set(["svg", "path", "g", "defs", "style", "title"]);
const decode = (text) =>
  text
    .replace(/&#x([0-9a-f]+);/gi, (_, hex) => String.fromCodePoint(parseInt(hex, 16)))
    .replace(/&#(\d+);/g, (_, dec) => String.fromCodePoint(Number(dec)));

/** The library icons in one file, so the picker draws all of them from one request: each icon's viewBox and path
 * data, `evenodd` where its SVG fills that way. Fails on SVG content a path list cannot carry. */
function symbols(icons) {
  const out = {};
  for (const name of icons) {
    const svg = readFileSync(resolve(ICONS, `${name}.svg`), "utf8").replace(/<!--[\s\S]*?-->/g, "");
    const unknown = [...svg.matchAll(/<([a-zA-Z][\w:-]*)/g)]
      .map((m) => m[1])
      .filter((tag) => !SVG_ELEMENTS.has(tag));
    if (unknown.length || /\stransform=/.test(svg))
      throw new Error(`${name}.svg: ${unknown[0] ?? "transform"} is not supported`);
    const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
    const paths = [...svg.matchAll(/<path\b([^>]*)>/g)].map((m) =>
      decode(m[1].match(/\sd="([^"]*)"/)?.[1] ?? "")
        .replace(/\s+/g, " ")
        .trim()
    );
    if (!viewBox || !paths.length || paths.some((d) => !d))
      throw new Error(`${name}.svg: no viewBox or path data`);
    out[name] = { viewBox, paths, ...(/fill-rule(:|=")\s*evenodd/.test(svg) ? { evenodd: true } : {}) };
  }
  return {
    licences:
      "Mapbox Maki and Temaki (CC0 1.0), Font Awesome Free (CC BY 4.0, https://fontawesome.com/license/free), Foundation Icon Fonts 3 (MIT); see README.md",
    icons: out,
  };
}

export async function generate() {
  const schema = read("goat-style.schema.json");
  const palettes = read("palettes.json");
  const icons = read("icons.json");
  const emoji = read("emoji.json");
  const emojiGroups = [...new Set(emoji.map((e) => e.group))];

  // json-schema-to-typescript names a type after its definition only when something refers to it, and the root
  // is a bare $ref; an object root referring to both documents gives LayerStyle and MapDocument their names.
  const { "x-defaults": defaults, $defs } = schema;
  const root = {
    type: "object",
    additionalProperties: false,
    properties: {
      layer_style: { $ref: "#/$defs/LayerStyle" },
      map_document: { $ref: "#/$defs/MapDocument" },
    },
    $defs,
  };
  const types = await compile(untitled(root), "GoatStyleDocuments", {
    bannerComment: BANNER,
    additionalProperties: false,
    unreachableDefinitions: true,
    style: { printWidth: 120 },
  });

  const catalog = Object.fromEntries(
    palettes.map((p) => [
      p.id,
      { name: p.name, kind: p.kind, colors: p.colors, ...(p.variants ? { variants: p.variants } : {}) },
    ])
  );

  const files = {
    "lib/style/generated/types.ts": types,
    "lib/style/generated/catalog.ts":
      `${BANNER}\nexport interface CataloguePalette {\n  name: string;\n  kind: "sequential" | "diverging" | "qualitative";\n` +
      `  colors: readonly string[];\n  variants?: Readonly<Record<number, readonly string[]>>;\n}\n\n` +
      `export const PALETTES: Readonly<Record<string, CataloguePalette>> = ${JSON.stringify(catalog, null, 2)};\n\n` +
      `export const ICON_NAMES: readonly string[] = ${JSON.stringify(icons, null, 2)};\n\n` +
      `export const ICON_GROUPS: readonly { id: string; labelKey: string; icons: readonly string[] }[] = ${JSON.stringify(
        schema["x-icon-groups"].map((g) => ({ id: g.id, labelKey: g.label_key, icons: g.icons })),
        null,
        2
      )};\n`,
    // The picker imports the emoji when it opens: a chunk of its own.
    "lib/style/generated/emoji.ts":
      `${BANNER}\nexport interface CatalogueEmoji {\n  code: string;\n  name: string;\n  group: string;\n  keywords: readonly string[];\n  /** Five toned codes, light to dark, for emoji with skin tones. */\n  tones?: readonly string[];\n}\n\n` +
      `export const EMOJI_GROUPS: readonly string[] = ${JSON.stringify(emojiGroups)};\n\n` +
      `export const EMOJI: readonly CatalogueEmoji[] = ${JSON.stringify(emoji)};\n`,
    "lib/style/generated/properties.ts": constant(
      "PROPERTY_KINDS",
      'Readonly<Record<string, "color" | "number" | "choice">>',
      propertyKinds(schema)
    ),
    "lib/style/generated/defaults.ts":
      constant("DEFAULTS", "Readonly<Record<string, unknown>>", defaults) +
      `\n/** From which zoom each H3 resolution draws under "auto" (goatlib AUTO_FROM_ZOOM); geoapi picks it per tile. */\n` +
      `export const H3_AUTO_FROM_ZOOM: readonly (readonly [number, number])[] = ${JSON.stringify(schema["x-h3-auto"])};\n`,
    "lib/style/generated/capabilities.ts": capabilitiesModule(schema),
    "public/assets/icons/maki/symbols.json": JSON.stringify(symbols(icons)),
  };
  // Formatted like the rest of the repository, so running prettier leaves the files as generated.
  const formatted = await Promise.all(
    Object.entries(files).map(async ([path, text]) => {
      const filepath = resolve(WEB, path);
      return [path, await format(text, { ...(await resolveConfig(filepath)), filepath })];
    })
  );
  return Object.fromEntries(formatted);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const files = await generate();
  for (const [path, content] of Object.entries(files)) {
    mkdirSync(dirname(resolve(WEB, path)), { recursive: true });
    writeFileSync(resolve(WEB, path), content);
  }
  console.log(`wrote ${Object.keys(files).length} files`);
}
